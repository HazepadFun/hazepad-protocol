// Asset pipeline: palette (k-means seeds snapped to real pixel coordinates), premultiplied logo resizes,
// traced favicon, hero crop, social card. Writes src/css/tokens.css (the only palette literal file) and dist/assets/*.
import fs from 'node:fs';
import sharp from 'sharp';
import { pmResize } from './pm.mjs';

import { fileURLToPath } from 'node:url';
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const P = p => ROOT + p;
const LOGO_RGBA = P('brand/LOGO HAZEPAD PNG...png');   // colourType 6, 3.6M pure-black transparent px
const LOGO_FLAT = P('brand/LOGO HAZEPAD PNG.png');      // colourType 6, fully opaque
const ART = P('reference/HAZEPAD 1.jpg.jpeg');
const BANNER = P('reference/SAMPUL HAZEPAD JPG.jpg.jpeg');
fs.mkdirSync(P('dist/assets'), { recursive: true });

const hex = (r, g, b) => '#' + [r, g, b].map(v => v.toString(16).padStart(2, '0')).join('').toUpperCase();
const cache = new Map();
async function raw(file) {
  if (!cache.has(file)) cache.set(file, await sharp(file).removeAlpha().raw().toBuffer({ resolveWithObject: true }));
  return cache.get(file);
}
// seed = k-means centroid of the source image; result = the real pixel closest to it
async function snap(file, seed) {
  const { data, info } = await raw(file);
  const t = [1, 3, 5].map(i => parseInt(seed.slice(i, i + 2), 16));
  let bi = 0, bd = 1e12;
  for (let i = 0; i < info.width * info.height; i++) {
    const d = (data[i*3]-t[0])**2 + (data[i*3+1]-t[1])**2 + (data[i*3+2]-t[2])**2;
    if (d < bd) { bd = d; bi = i; if (!d) break; }
  }
  return { hex: hex(data[bi*3], data[bi*3+1], data[bi*3+2]), x: bi % info.width, y: Math.floor(bi / info.width) };
}

const rel = f => f.replace(ROOT, '');
const SPEC = [
  ['ink',    LOGO_FLAT, '#1C1411', 'logo field, k-means cluster 1 (90.6% of pixels)'],
  ['white',  LOGO_FLAT, '#FDFDFD', 'logo mark, k-means cluster 2'],
  ['deep',   ART,       '#170C06', 'art 1, k-means cluster 1 (45.7%)'],
  ['brown',  ART,       '#3B200F', 'art 1, k-means cluster 2'],
  ['clay',   ART,       '#72401F', 'art 1, k-means cluster 3'],
  ['paper',  ART,       '#E3CFB6', 'art 1, k-means cluster 4'],
  ['amber',  ART,       '#D08D3F', 'art 1, k-means cluster 5'],
  ['gold',   ART,       '#FFDC5D', 'art 1, headline colour, dominant saturated bucket'],
  ['flame',  ART,       '#F98A30', 'art 1, ember bucket'],
  ['sky',    BANNER,    '#7FC2EC', 'banner, k-means sky cluster'],
  ['mist',   BANNER,    '#BFDEF0', 'banner, k-means pale sky cluster'],
  ['stone',  BANNER,    '#5A4C41', 'banner, k-means cluster 1'],
  ['moss',   ART,       '#4E7F2C', 'art 1, voxel tree canopy'],
];
const pal = {};
for (const [name, file, seed, note] of SPEC) pal[name] = { ...(await snap(file, seed)), file: rel(file), note };

let css = `/* Palette tokens. The ONLY file allowed to contain colour literals.
   Provenance: every value below is the exact RGB of a real pixel in a brand/ or reference/ asset.
   Method: k-means (k=6..14) over opaque pixels, each centroid snapped to the nearest real pixel in the
   source; coordinates are x,y in the source raster. Re-generated by tools/assets.mjs. */
:root {
`;
for (const [k, v] of Object.entries(pal)) css += `  --${k}: ${v.hex}; /* ${v.file} @ ${v.x},${v.y}: ${v.note} */\n`;
css += `}\n`;
fs.writeFileSync(P('src/css/tokens.css'), css);

// ---- logos: premultiplied resize because the transparent PNG carries pure-black RGB under alpha 0
// crop to mark bounds first so small sizes keep the mark large
const full = await sharp(LOGO_RGBA).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
let x0 = 1e9, y0 = 1e9, x1 = 0, y1 = 0;
for (let y = 0; y < full.info.height; y++) for (let x = 0; x < full.info.width; x++) if (full.data[(y*full.info.width+x)*4+3] > 128) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
const bw = x1 - x0 + 1, bh = y1 - y0 + 1, side = Math.max(bw, bh);
const pad = Math.round(side * 0.04), S = side + pad * 2;
const cropped = await sharp(LOGO_RGBA).extract({ left: x0, top: y0, width: bw, height: bh })
  .extend({ top: Math.floor((S - bh) / 2), bottom: Math.ceil((S - bh) / 2), left: Math.floor((S - bw) / 2), right: Math.ceil((S - bw) / 2), background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .png().toBuffer();
const alphaPlane = async (input, size) => { const r = await pmResize(input, size); const a = Buffer.alloc(size * size); for (let i = 0; i < a.length; i++) a[i] = r[i*4+3]; return a; };
const tint = async (buf, hexv, size) => {
  const a = await alphaPlane(buf, size);
  const c = [1, 3, 5].map(i => parseInt(hexv.slice(i, i + 2), 16));
  return sharp({ create: { width: size, height: size, channels: 3, background: { r: c[0], g: c[1], b: c[2] } } }).joinChannel(a, { raw: { width: size, height: size, channels: 1 } }).png({ compressionLevel: 9 });
};
for (const s of [64, 128, 256, 512]) {
  await (await tint(cropped, pal.white.hex, s)).toFile(P(`dist/assets/logo-${s}.png`));
}
await (await tint(cropped, pal.ink.hex, 128)).toFile(P('dist/assets/logo-ink-128.png'));
// touch icon: mark on ink field
{ const m = await (await tint(cropped, pal.white.hex, 128)).toBuffer();
  const c = [1, 3, 5].map(i => parseInt(pal.ink.hex.slice(i, i + 2), 16));
  await sharp({ create: { width: 180, height: 180, channels: 3, background: { r: c[0], g: c[1], b: c[2] } } }).composite([{ input: m, left: 26, top: 26 }]).png().toFile(P('dist/assets/apple-touch-icon.png')); }

// ---- favicon: 32x32 pixel grid traced from the logo's alpha raster (mark placed in a 24x24 area inside the 32 grid)
{
  const g = 24, off = 4;
  const a = await alphaPlane(cropped, g);
  let d = '';
  for (let y = 0; y < g; y++) { let x = 0; while (x < g) { if (a[y*g+x] >= 128) { let w = 1; while (x + w < g && a[y*g+x+w] >= 128) w++; d += `M${x+off} ${y+off}h${w}v1h-${w}z`; x += w; } else x++; } }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32" width="32" height="32" shape-rendering="crispEdges"><rect width="32" height="32" rx="6" fill="${pal.ink.hex}"/><path fill="${pal.white.hex}" d="${d}"/></svg>\n`;
  if (/--/.test(svg)) throw new Error('favicon contains a double hyphen');
  fs.writeFileSync(P('dist/favicon.svg'), svg);
}

// ---- hero art: right-hand mine, text side cropped away
await sharp(ART).extract({ left: 690, top: 0, width: 910, height: 900 }).webp({ quality: 80 }).toFile(P('dist/assets/mine.webp'));
await sharp(ART).resize(1200, 630, { fit: 'cover', position: 'right' }).jpeg({ quality: 84, mozjpeg: true }).toFile(P('dist/assets/og.jpg'));
fs.writeFileSync(P('tools/palette.json'), JSON.stringify(pal, null, 1));
console.log('palette', Object.entries(pal).map(([k, v]) => `${k}=${v.hex}@${v.x},${v.y}`).join(' '));
console.log('mark bbox', x0, y0, x1, y1);
